SELECT COUNT(*) AS Days
FROM air_fangzhicheng
WHERE SO2 IS NOT NULL
	or NO2 IS NOT NULL
	or PM10 IS NOT NULL
	or CO IS NOT NULL
	or PM25 IS NOT NULL;

-- 无监测结果的天数
